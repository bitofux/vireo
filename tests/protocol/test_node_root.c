/* 测试参考只按固定wire offset写字节和CRC，不调用被测encoder/公共codec。 */
static void put16(unsigned char *p, uint16_t value) {
    p[0] = (unsigned char)(value >> 8); p[1] = (unsigned char)value;
}
static void put32(unsigned char *p, uint32_t value) {
    for (size_t i = 0; i < 4; ++i) p[i] = (unsigned char)(value >> (24U - (unsigned)i * 8U));
}
static uint32_t get32(unsigned char const *p) {
    uint32_t value = 0;
    for (size_t i = 0; i < 4; ++i) value = (value << 8) | p[i];
    return value;
}
static void crc(unsigned char *wire, size_t size) {
    uint32_t value = UINT32_MAX;
    for (size_t i = 0; i < size; ++i) {
        if (i >= 28 && i < 32) continue;
        value ^= wire[i];
        for (unsigned j = 0; j < 8; ++j)
            value = (value >> 1) ^ ((value & 1U) != 0 ? UINT32_C(0x82f63b78) : 0);
    }
    put32(wire + 28, value ^ UINT32_MAX);
}
static bool allowed(uint16_t status) {
    /* 独立数值集合，不从生产switch或宏表生成。 */
    static uint16_t const values[] = {0,1001,1002,1004,1005,1006,1007,1008,1101,
                                     1901,1902,1906,1907,1908};
    for (size_t i = 0; i < sizeof values / sizeof values[0]; ++i)
        if (values[i] == status) return true;
    return false;
}
static void make(unsigned char *wire, bool response, uint16_t status) {
    size_t const size = response && status == 0 ? 44 : 32;
    memset(wire, 0, size);
    wire[0] = 'V'; wire[1] = 'I'; wire[2] = 'R'; wire[3] = 'E'; wire[4] = 1; wire[5] = 32;
    put16(wire + 6, 0x0406); put16(wire + 8, response ? 1 : 0);
    put16(wire + 10, status); put32(wire + 12, (uint32_t)(size - 32));
    put32(wire + 16, 1); put32(wire + 20, !response || status == 0 ? 2 : 0);
    if (size == 44) { put16(wire + 32, 0x0401); put16(wire + 34, 8); wire[43] = 42; }
    crc(wire, size);
}

/* 任何格式失败都保留整个宿主对象含padding，合法错误帧仍是decode成功。 */
static void decode(unsigned char const *wire, size_t size, bool response,
    vireo_node_root_issue_t expected) {
    vireo_node_root_issue_t issue = VIREO_NODE_ROOT_ISSUE_VALUE;
    vireo_result_t result;
    unsigned char encoded[64], before[64]; size_t length = 999;
    memset(encoded, 0xa5, sizeof encoded); memcpy(before, encoded, sizeof before);
    errno = EDOM;
    if (response) {
        vireo_node_root_response_t value, old;
        memset(&value, 0xa5, sizeof value); memcpy(&old, &value, sizeof old);
        result = vireo_node_root_response_decode(wire, size, &value, &issue);
        CHECK(errno == EDOM && issue == expected);
        if (expected == VIREO_NODE_ROOT_ISSUE_NONE) {
            CHECK(result == VIREO_OK && value.sequence == get32(wire + 16));
            CHECK(value.session_handle == get32(wire + 20));
            CHECK(allowed(value.status));
            CHECK(value.status == 0 ? value.root_node_id != 0 : value.root_node_id == 0);
            CHECK(vireo_node_root_response_encode(&value, encoded, sizeof encoded, &length) == VIREO_OK);
        } else CHECK(result == VIREO_RESULT_PROTOCOL && memcmp(&old, &value, sizeof old) == 0);
    } else {
        vireo_node_root_request_t value, old;
        memset(&value, 0xa5, sizeof value); memcpy(&old, &value, sizeof old);
        result = vireo_node_root_request_decode(wire, size, &value, &issue);
        CHECK(errno == EDOM && issue == expected);
        if (expected == VIREO_NODE_ROOT_ISSUE_NONE) {
            CHECK(result == VIREO_OK && value.sequence == get32(wire + 16));
            CHECK(value.session_handle == get32(wire + 20));
            CHECK(vireo_node_root_request_encode(&value, encoded, sizeof encoded, &length) == VIREO_OK);
        } else CHECK(result == VIREO_RESULT_PROTOCOL && memcmp(&old, &value, sizeof old) == 0);
    }
    CHECK(errno == EDOM);
    if (expected == VIREO_NODE_ROOT_ISSUE_NONE) {
        CHECK(length == size && memcmp(encoded, wire, size) == 0);
        CHECK(memcmp(encoded + size, before + size, sizeof encoded - size) == 0);
    }
}

static void golden_vectors(void) {
    for (size_t i = 0; i < sizeof goldens / sizeof goldens[0]; ++i) {
        golden_t const *g = &goldens[i];
        decode(g->wire, g->size, g->response, g->issue);
    }
}

static void states_and_flags(void) {
    unsigned char wire[64], old[64];
    for (uint32_t i = 0; i <= UINT16_MAX; ++i) {
        uint16_t const status = (uint16_t)i;
        make(wire, true, status);
        bool const valid = allowed(status);
        size_t const size = status == 0 ? 44 : 32;
        vireo_node_root_issue_t const expected = valid ? VIREO_NODE_ROOT_ISSUE_NONE :
            vireo_status_is_known(status) ? VIREO_NODE_ROOT_ISSUE_ENVELOPE : VIREO_NODE_ROOT_ISSUE_HEADER;
        decode(wire, size, true, expected);
        vireo_node_root_response_t value = {.status = status, .sequence = 1,
            .session_handle = status == 0 ? 2 : 0, .root_node_id = status == 0 ? 42 : 0};
        size_t length = 999; memset(wire, 0xa5, sizeof wire); memcpy(old, wire, sizeof old);
        errno = EDOM;
        vireo_result_t const result = vireo_node_root_response_encode(&value, wire, sizeof wire, &length);
        CHECK(errno == EDOM && result == (valid ? VIREO_OK : VIREO_RESULT_INVALID_ARGUMENT));
        if (!valid) CHECK(length == 999 && memcmp(wire, old, sizeof wire) == 0);
    }
    for (uint32_t i = 0; i <= UINT16_MAX; ++i) {
        make(wire, false, 0); put16(wire + 8, (uint16_t)i); crc(wire, 32);
        vireo_node_root_issue_t const req = i == 0 ? VIREO_NODE_ROOT_ISSUE_NONE :
            (i & ~UINT32_C(0x003f)) != 0 || (i & UINT32_C(0x0021)) != 0 ?
                VIREO_NODE_ROOT_ISSUE_HEADER : VIREO_NODE_ROOT_ISSUE_ENVELOPE;
        decode(wire, 32, false, req);
        make(wire, true, 0); put16(wire + 8, (uint16_t)i); crc(wire, 44);
        vireo_node_root_issue_t const res = i == 1 ? VIREO_NODE_ROOT_ISSUE_NONE :
            (i & ~UINT32_C(0x003f)) != 0 || (i & 1U) == 0 ?
                VIREO_NODE_ROOT_ISSUE_HEADER : VIREO_NODE_ROOT_ISSUE_ENVELOPE;
        decode(wire, 44, true, res);
    }
}

static void capacity_and_values(void) {
    vireo_node_root_request_t request = {.sequence = UINT32_MAX, .session_handle = UINT32_MAX};
    vireo_node_root_response_t response = {.status = 0, .sequence = UINT32_MAX,
        .session_handle = UINT32_MAX, .root_node_id = UINT64_MAX};
    unsigned char wire[64], old[64];
    for (unsigned mode = 0; mode < 3; ++mode) {
        size_t const size = mode == 1 ? 44 : 32;
        if (mode == 2) { response.status = 1101; response.session_handle = 0; response.root_node_id = 0; }
        for (size_t cap = 0; cap <= sizeof wire; ++cap) {
            memset(wire, 0xa5, sizeof wire); memcpy(old, wire, sizeof old); size_t length = 999;
            errno = ERANGE;
            vireo_result_t const result = mode == 0 ?
                vireo_node_root_request_encode(&request, wire, cap, &length) :
                vireo_node_root_response_encode(&response, wire, cap, &length);
            CHECK(errno == ERANGE && result == (cap < size ? VIREO_RESULT_RANGE : VIREO_OK));
            if (cap < size) CHECK(length == 999 && memcmp(wire, old, sizeof wire) == 0);
            else {
                CHECK(length == size && memcmp(wire + size, old + size, sizeof wire - size) == 0);
                decode(wire, length, mode != 0, VIREO_NODE_ROOT_ISSUE_NONE);
            }
        }
    }
    /* 宿主非法值必须先于容量判定，失败整区/长度保持；不能只测试wire非法帧。 */
    for (unsigned i = 0; i < 6; ++i) {
        response = (vireo_node_root_response_t){.status = 0, .sequence = 1, .session_handle = 2, .root_node_id = 42};
        switch (i) {
        case 0: response.sequence = 0; break;
        case 1: response.session_handle = 0; break;
        case 2: response.root_node_id = 0; break;
        case 3: response.status = 1201; break;
        case 4: response.status = 1101; response.root_node_id = 0; break;
        default: response.status = 1101; response.session_handle = 0; break;
        }
        for (size_t cap = 0; cap <= sizeof wire; ++cap) {
            memset(wire, 0xa5, sizeof wire); memcpy(old, wire, sizeof old); size_t length = 999;
            errno = EDOM;
            CHECK(vireo_node_root_response_encode(&response, wire, cap, &length) == VIREO_RESULT_INVALID_ARGUMENT);
            CHECK(errno == EDOM && length == 999 && memcmp(old, wire, sizeof wire) == 0);
        }
    }
    request.sequence = 0; size_t length = 999; memcpy(old, wire, sizeof old); errno = EDOM;
    CHECK(vireo_node_root_request_encode(&request, wire, 0, &length) == VIREO_RESULT_INVALID_ARGUMENT);
    CHECK(errno == EDOM && length == 999 && memcmp(old, wire, sizeof wire) == 0);
}

static void null_arguments(void) {
    vireo_node_root_request_t request = {.sequence = 1, .session_handle = 2};
    vireo_node_root_response_t response = {.status = 0, .sequence = 1, .session_handle = 2, .root_node_id = 42};
    vireo_node_root_request_t old_request;
    vireo_node_root_response_t old_response;
    unsigned char wire[64], old_wire[64];
    for (unsigned which = 0; which < 3; ++which) {
        request = (vireo_node_root_request_t){.sequence = 1, .session_handle = 2};
        response = (vireo_node_root_response_t){.status = 0, .sequence = 1, .session_handle = 2, .root_node_id = 42};
        memset(wire, 0xa5, sizeof wire); memcpy(old_wire, wire, sizeof wire);
        size_t length = 999; errno = EDOM;
        CHECK(vireo_node_root_request_encode(which == 0 ? NULL : &request,
            which == 1 ? NULL : wire, sizeof wire, which == 2 ? NULL : &length) == VIREO_RESULT_INVALID_ARGUMENT);
        CHECK(errno == EDOM && length == 999 && memcmp(wire, old_wire, sizeof wire) == 0);
        CHECK(vireo_node_root_response_encode(which == 0 ? NULL : &response,
            which == 1 ? NULL : wire, sizeof wire, which == 2 ? NULL : &length) == VIREO_RESULT_INVALID_ARGUMENT);
        CHECK(errno == EDOM && length == 999 && memcmp(wire, old_wire, sizeof wire) == 0);
        memset(&request, 0xa5, sizeof request); memcpy(&old_request, &request, sizeof request);
        memset(&response, 0xa5, sizeof response); memcpy(&old_response, &response, sizeof response);
        vireo_node_root_issue_t issue = VIREO_NODE_ROOT_ISSUE_VALUE;
        CHECK(vireo_node_root_request_decode(which == 0 ? NULL : wire, 0,
            which == 1 ? NULL : &request, which == 2 ? NULL : &issue) == VIREO_RESULT_INVALID_ARGUMENT);
        CHECK(errno == EDOM && (which == 2 || issue == VIREO_NODE_ROOT_ISSUE_NONE));
        CHECK(memcmp(&request, &old_request, sizeof request) == 0);
        issue = VIREO_NODE_ROOT_ISSUE_VALUE;
        CHECK(vireo_node_root_response_decode(which == 0 ? NULL : wire, 0,
            which == 1 ? NULL : &response, which == 2 ? NULL : &issue) == VIREO_RESULT_INVALID_ARGUMENT);
        CHECK(errno == EDOM && (which == 2 || issue == VIREO_NODE_ROOT_ISSUE_NONE));
        CHECK(memcmp(&response, &old_response, sizeof response) == 0);
    }
}

static void lengths_and_corruption(void) {
    unsigned char wire[64];
    for (unsigned mode = 0; mode < 2; ++mode) {
        bool const response = mode != 0; size_t const normal = response ? 44 : 32;
        for (size_t size = 0; size <= sizeof wire; ++size) {
            memset(wire, 0, sizeof wire); make(wire, response, 0);
            vireo_node_root_issue_t const expected = size < 32 ? VIREO_NODE_ROOT_ISSUE_HEADER :
                size == normal ? VIREO_NODE_ROOT_ISSUE_NONE : VIREO_NODE_ROOT_ISSUE_ENVELOPE;
            decode(wire, size, response, expected);
        }
        make(wire, response, 0);
        for (size_t i = 0; i < normal; ++i) {
            for (unsigned bit = 0; bit < 8; ++bit) {
                wire[i] ^= (unsigned char)(1U << bit);
                vireo_node_root_issue_t issue;
                vireo_result_t result;
                vireo_node_root_request_t request, old_request;
                vireo_node_root_response_t value, old_value;
                memset(&request, 0xa5, sizeof request); memcpy(&old_request, &request, sizeof request);
                memset(&value, 0xa5, sizeof value); memcpy(&old_value, &value, sizeof value);
                errno = EDOM;
                result = response ? vireo_node_root_response_decode(wire, normal, &value, &issue) :
                    vireo_node_root_request_decode(wire, normal, &request, &issue);
                CHECK(errno == EDOM && result == VIREO_RESULT_PROTOCOL && issue != VIREO_NODE_ROOT_ISSUE_NONE);
                CHECK(response ? memcmp(&value, &old_value, sizeof value) == 0 :
                    memcmp(&request, &old_request, sizeof request) == 0);
                wire[i] ^= (unsigned char)(1U << bit);
            }
        }
    }
    /* body逐长度覆盖：CRC有效的空/短/多字段都必须拒绝，不能只依赖CRC拒绝。 */
    for (size_t body = 0; body <= 12; ++body) {
        make(wire, true, 0); put32(wire + 12, (uint32_t)body); crc(wire, 32 + body);
        decode(wire, 32 + body, true, body == 12 ? VIREO_NODE_ROOT_ISSUE_NONE : VIREO_NODE_ROOT_ISSUE_FIELDS);
    }
}

static void registry_and_base_codec(void) {
    CHECK(VIREO_COMMAND_NODE_ROOT == 0x0406 && VIREO_NODE_ROOT_TLV_NODE_ID == 0x0401);
    errno = EDOM;
    CHECK(vireo_command_is_known(VIREO_COMMAND_NODE_ROOT));
    CHECK(!vireo_command_is_reserved(VIREO_COMMAND_NODE_ROOT));
    CHECK(strcmp(vireo_command_name(VIREO_COMMAND_NODE_ROOT), "node_root") == 0 && errno == EDOM);
    unsigned char wire[64]; make(wire, false, 0);
    vireo_protocol_header_t header; vireo_protocol_codec_issue_t issue;
    CHECK(vireo_protocol_header_decode(wire, 32, &header, &issue) == VIREO_OK);
    CHECK(vireo_protocol_request_header_validate(&header, &issue) == VIREO_OK);
    make(wire, true, 0);
    CHECK(vireo_protocol_header_decode(wire, 44, &header, &issue) == VIREO_OK);
    CHECK(vireo_protocol_response_header_validate(&header, &issue) == VIREO_OK);
}

int main(void) {
    golden_vectors(); states_and_flags(); capacity_and_values(); null_arguments();
    lengths_and_corruption(); registry_and_base_codec();
    printf("NODE_ROOT: 44 independent goldens, 65536 statuses, 65536 flags per direction, %zu checks passed\n", checks);
    return 0;
}
