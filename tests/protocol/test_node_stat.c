static unsigned long checks;
#define CHECK(c) do { ++checks; if (!(c)) { fprintf(stderr, "check failed line %d: %s\n", __LINE__, #c); assert(c); } } while (0)
#define CALL(expr, result) do { errno = EDOM; CHECK((expr) == (result)); CHECK(errno == EDOM); } while (0)

/* 重算完整帧的长度/CRC；schema反例不会被旧CRC提前遮住。 */
static void repair(unsigned char *wire, size_t n) {
    CHECK(n >= 32 && n < 1024);
    uint32_t const body = (uint32_t)(n - 32);
    for (size_t i = 0; i < 4; ++i) wire[12 + i] = (unsigned char)(body >> (24 - 8 * i));
    uint32_t crc;
    CHECK(vireo_protocol_frame_crc32c_calculate(wire, 32, wire + 32, n - 32, &crc) == VIREO_OK);
    for (size_t i = 0; i < 4; ++i) wire[28 + i] = (unsigned char)(crc >> (24 - 8 * i));
}

static bool allowed(unsigned status) {
    switch (status) {
    case 0: case 1001: case 1002: case 1004: case 1005: case 1006: case 1007: case 1008:
    case 1101: case 1201: case 1901: case 1902: case 1906: case 1907: case 1908: return true;
    default: return false;
    }
}

/* 失败比较整个对象表示，包括padding；成功对象只比较语义成员。 */
static void rejected(bool response, unsigned char const *wire, size_t n, vireo_node_stat_issue_t expected) {
    vireo_node_stat_issue_t issue = VIREO_NODE_STAT_ISSUE_NONE;
    if (response) {
        vireo_node_stat_response_t out, old; memset(&out, 0xa5, sizeof out); memcpy(&old, &out, sizeof out);
        CALL(vireo_node_stat_response_decode(wire, n, &out, &issue), VIREO_RESULT_PROTOCOL);
        CHECK(memcmp(&out, &old, sizeof out) == 0);
    } else {
        vireo_node_stat_request_t out, old; memset(&out, 0xa5, sizeof out); memcpy(&old, &out, sizeof out);
        CALL(vireo_node_stat_request_decode(wire, n, &out, &issue), VIREO_RESULT_PROTOCOL);
        CHECK(memcmp(&out, &old, sizeof out) == 0);
    }
    CHECK(issue != VIREO_NODE_STAT_ISSUE_NONE);
    if (expected != VIREO_NODE_STAT_ISSUE_NONE) CHECK(issue == expected);
}

static bool bytes_zero(unsigned char const *p, size_t n) {
    for (size_t i = 0; i < n; ++i) if (p[i] != 0) return false;
    return true;
}

/* 对照预期业务数值，而非仅用第二次decode验证第一次encode。 */
static void golden_values(size_t i, vireo_node_stat_response_t const *v) {
    vireo_node_stat_metadata_t const *m = &v->metadata;
    CHECK(v->sequence == 1);
    if (i >= 9) {
        CHECK(v->status != VIREO_STATUS_OK && allowed(v->status) && v->session_handle == 0);
        CHECK(m->node_id == 0 && !m->has_parent && m->parent_id == 0 && m->type == 0 && m->size == 0);
        CHECK(m->name_length == 0 && bytes_zero(m->name, 255) && !m->has_object_hash && bytes_zero(m->object_hash, 32));
        CHECK(m->created_at_ms == 0 && m->updated_at_ms == 0); return;
    }
    CHECK(v->status == 0 && v->session_handle == 2);
    if (i == 3) {
        CHECK(m->node_id == 42 && !m->has_parent && m->parent_id == 0 && m->name_length == 0);
        CHECK(m->type == 1 && m->size == 0 && m->created_at_ms == 1000 && m->updated_at_ms == 1000);
    } else {
        CHECK(m->has_parent && m->parent_id == 42);
        if (i == 4 || i == 7) {
            CHECK(m->node_id == 43 && m->type == 1 && m->size == 0);
            CHECK(m->name_length == (i == 4 ? 255U : 3U));
            if (i == 4) for (size_t j = 0; j < 255; ++j) CHECK(m->name[j] == 0x80);
            else CHECK(memcmp(m->name, "\t\n\\", 3) == 0);
            CHECK(m->created_at_ms == (i == 4 ? 1000U : 0U) && m->updated_at_ms == m->created_at_ms);
        } else {
            CHECK(m->node_id == 44 && m->type == 2 && m->has_object_hash);
            if (i == 6) {
                CHECK(m->name_length == 1 && m->name[0] == 'x' && m->size == 0);
                CHECK(bytes_zero(m->object_hash, 32) && m->created_at_ms == 0 && m->updated_at_ms == 0);
            } else {
                CHECK(m->name_length == 255 && m->size == UINT64_MAX && m->created_at_ms == 0 && m->updated_at_ms == UINT64_MAX);
                for (size_t j = 0; j < 255; ++j) CHECK(m->name[j] == 0xff);
                for (size_t j = 0; j < 32; ++j) CHECK(m->object_hash[j] == j);
            }
        }
    }
    CHECK(bytes_zero(m->name + m->name_length, 255 - m->name_length));
    if (m->type == 1) CHECK(!m->has_object_hash && bytes_zero(m->object_hash, 32));
}

